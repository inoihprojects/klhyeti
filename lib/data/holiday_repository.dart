/// A holiday calendar imported from an .ics file.
class ImportedHolidays {
  final int id;
  final String name;
  final int dayCount;

  const ImportedHolidays(this.id, this.name, this.dayCount);
}

/// Which days are holidays, from the regions switched on in Settings and
/// any imported .ics calendars. Opt-in: nothing is on until chosen.
///
/// Region tables are bundled assets and imported days live in the local
/// database, so nothing here uses the network. Like other settings, the
/// choice stays on this device and is not synced.
class HolidayRepository extends ChangeNotifier {
  final Database _db;
  final AssetBundle _assets;

  HolidayRepository(this._db, {AssetBundle? assets})
      : _assets = assets ?? rootBundle;

  static const String _kRegions = 'holiday_regions';

  Set<String> _enabled = {};
  final Map<String, Map<int, List<String>>> _regionDays = {};
  List<ImportedHolidays> _imported = const [];
  Map<int, List<String>> _importedDays = const {};

  /// Everything switched on, merged: yyyymmdd to names.
  Map<int, List<String>> _merged = const {};

  Set<String> get enabledRegions => Set.unmodifiable(_enabled);
  List<ImportedHolidays> get imported => List.unmodifiable(_imported);

  /// The holidays on [day] (its time is ignored), empty if none.
  List<String> namesOn(DateTime day) => _merged[ymd(day)] ?? const [];

  Future<void> load() async {
    final rows = await _db.query('settings',
        where: 'key = ?', whereArgs: [_kRegions], limit: 1);
    final stored = rows.isEmpty ? '' : rows.first['value']! as String;
    _enabled = stored
        .split(',')
        .where((code) => holidayRegions.any((r) => r.code == code))
        .toSet();
    for (final code in _enabled) {
      await _loadRegion(code);
    }
    await _loadImported();
    _rebuild();
  }

  Future<void> setRegionEnabled(String code, bool enabled) async {
    if (enabled) {
      await _loadRegion(code);
      _enabled.add(code);
    } else {
      _enabled.remove(code);
    }
    await _db.insert(
      'settings',
      {'key': _kRegions, 'value': (_enabled.toList()..sort()).join(',')},
      conflictAlgorithm: ConflictAlgorithm.replace,
    );
    _rebuild();
  }

  /// Stores the days found in an .ics file as a new imported calendar and
  /// returns how many there were; nothing is stored if there were none.
  Future<int> importIcs(String fallbackName, String content) async {
    final calendar = parseIcs(content);
    if (calendar.days.isEmpty) return 0;
    await _db.transaction((txn) async {
      final id = await txn.insert('holiday_calendars', {
        'name': calendar.name ?? fallbackName,
        'imported_at': DateTime.now().toUtc().millisecondsSinceEpoch,
      });
      final batch = txn.batch();
      for (final day in calendar.days) {
        batch.insert('holiday_days', {
          'calendar_id': id,
          'day': day.day,
          'name': day.name,
        });
      }
      await batch.commit(noResult: true);
    });
    await _loadImported();
    _rebuild();
    return calendar.days.length;
  }

  Future<void> removeImported(int id) async {
    await _db.transaction((txn) async {
      await txn.delete('holiday_days', where: 'calendar_id = ?', whereArgs: [id]);
      await txn.delete('holiday_calendars', where: 'id = ?', whereArgs: [id]);
    });
    await _loadImported();
    _rebuild();
  }

  Future<void> _loadRegion(String code) async {
    if (_regionDays.containsKey(code)) return;
    final json = jsonDecode(
        await _assets.loadString('assets/holidays/$code.json'))
        as Map<String, Object?>;
    final names = (json['names']! as List).cast<String>();
    final days = <int, List<String>>{};
    for (final entry in json['days']! as List) {
      final pair = entry as List;
      days.putIfAbsent(pair[0] as int, () => []).add(names[pair[1] as int]);
    }
    _regionDays[code] = days;
  }

  Future<void> _loadImported() async {
    final calendars = await _db.rawQuery('''
      SELECT c.id, c.name, COUNT(d.day) AS days
      FROM holiday_calendars c
      LEFT JOIN holiday_days d ON d.calendar_id = c.id
      GROUP BY c.id
      ORDER BY c.imported_at
    ''');
    _imported = [
      for (final row in calendars)
        ImportedHolidays(
            row['id']! as int, row['name']! as String, row['days']! as int),
    ];
    final days = <int, List<String>>{};
    for (final row in await _db.query('holiday_days')) {
      days.putIfAbsent(row['day']! as int, () => []).add(row['name']! as String);
    }
    _importedDays = days;
  }

  void _rebuild() {
    final merged = <int, List<String>>{};
    void addAll(Map<int, List<String>> source) {
      source.forEach((day, names) {
        final list = merged.putIfAbsent(day, () => []);
        for (final name in names) {
          if (!list.contains(name)) list.add(name);
        }
      });
    }

    for (final region in holidayRegions) {
      if (_enabled.contains(region.code)) addAll(_regionDays[region.code]!);
    }
    addAll(_importedDays);
    _merged = merged;
    notifyListeners();
  }
}
